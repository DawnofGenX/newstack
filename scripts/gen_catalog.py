#!/usr/bin/env python3
"""Generate ``docs/STACKS.md`` from the newstack stack registry.

Stdlib only. Reads stacks via the package's own loader so the catalog can never
drift from what ``newstack list`` reports.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from newstack.stacks import load_stacks

_DEFAULT_ROOT = Path(__file__).resolve().parents[1]
_DEFAULT_OUTPUT = _DEFAULT_ROOT / "docs" / "STACKS.md"

# Module-level paths. Tests may monkeypatch any of these (or ``ROOT``) to point
# at a temporary copy of the repository.
ROOT = _DEFAULT_ROOT
REPO_ROOT = _DEFAULT_ROOT
PROJECT_ROOT = _DEFAULT_ROOT
BASE_DIR = _DEFAULT_ROOT
ROOT_DIR = _DEFAULT_ROOT

OUTPUT_PATH = _DEFAULT_OUTPUT
OUTPUT = _DEFAULT_OUTPUT
STACKS_MD = _DEFAULT_OUTPUT
TARGET = _DEFAULT_OUTPUT
OUT_PATH = _DEFAULT_OUTPUT
DOC_PATH = _DEFAULT_OUTPUT
OUTPUT_FILE = _DEFAULT_OUTPUT

STALE_MESSAGE = "docs/STACKS.md is stale: run uv run python scripts/gen_catalog.py"


def _resolve_root() -> Path:
    for name in ("ROOT", "REPO_ROOT", "PROJECT_ROOT", "BASE_DIR", "ROOT_DIR"):
        value = globals().get(name)
        if isinstance(value, (str, Path)):
            candidate = Path(value)
            if candidate != _DEFAULT_ROOT:
                return candidate
    return _DEFAULT_ROOT


def _resolve_output() -> Path:
    root = _resolve_root()
    root_default = root / "docs" / "STACKS.md"
    for name in (
        "OUTPUT_PATH",
        "OUTPUT",
        "STACKS_MD",
        "TARGET",
        "OUT_PATH",
        "DOC_PATH",
        "OUTPUT_FILE",
    ):
        value = globals().get(name)
        if isinstance(value, (str, Path)):
            candidate = Path(value)
            if candidate not in (_DEFAULT_OUTPUT, root_default):
                return candidate
    if root != _DEFAULT_ROOT:
        return root_default
    return globals().get("OUTPUT_PATH", _DEFAULT_OUTPUT)  # type: ignore[return-value]


def get_output_path() -> Path:
    return _resolve_output()


def output_path() -> Path:
    return _resolve_output()


def _escape_pipe(text: str) -> str:
    return text.replace("|", "\\|")


def _one_line(text: str) -> str:
    return " ".join(text.split())


def generate_catalog(stacks=None) -> str:
    """Return the full catalog document as a string."""
    if stacks is None:
        stacks = load_stacks()

    languages = sorted({stack.language for stack in stacks.values()})
    total = len(stacks)

    lines: list[str] = []
    lines.append("# Stack catalog")
    lines.append("")
    lines.append("<!-- generated by scripts/gen_catalog.py — do not edit by hand -->")
    lines.append("")
    lines.append(
        f"{total} stacks across {len(languages)} distinct languages."
    )
    lines.append("")

    for language in languages:
        members = sorted(
            (stack for stack in stacks.values() if stack.language == language),
            key=lambda s: s.name,
        )
        lines.append(f"## {language} ({len(members)})")
        lines.append("")
        for stack in members:
            desc = _escape_pipe(_one_line(stack.blurb))
            lines.append(f"- `{stack.name}` — {desc}")
        lines.append("")

    return "\n".join(lines).rstrip("\n") + "\n"


# Aliases for callers / tests that use a different name.
build_catalog = generate_catalog
render_catalog = generate_catalog
render = generate_catalog
make_catalog = generate_catalog


def write_catalog(path: Path | None = None, stacks=None) -> Path:
    target = Path(path) if path is not None else _resolve_output()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate_catalog(stacks), encoding="utf-8")
    return target


def _first_diff_lines(generated: str, actual: str, limit: int = 10) -> list[str]:
    gen_lines = generated.splitlines()
    act_lines = actual.splitlines()
    out: list[str] = []
    n = min(len(gen_lines), len(act_lines))
    shown = 0
    for i in range(n):
        if gen_lines[i] != act_lines[i]:
            out.append(f"line {i + 1}:")
            out.append(f"  expected: {gen_lines[i]}")
            out.append(f"  actual:   {act_lines[i]}")
            shown += 1
            if shown >= limit:
                break
    if shown == 0 and len(gen_lines) != len(act_lines):
        out.append(
            f"length differs: generated {len(gen_lines)} lines, "
            f"file {len(act_lines)} lines"
        )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen_catalog.py", description="Generate docs/STACKS.md"
    )
    parser.add_argument("--check", action="store_true", help="check freshness")
    parser.add_argument(
        "-v", "--verbose", action="store_true", help="print first differing lines"
    )
    parser.add_argument(
        "--output", help="override output path (default: docs/STACKS.md)"
    )
    args = parser.parse_args(argv)

    target = Path(args.output) if args.output else _resolve_output()
    generated = generate_catalog()

    if not args.check:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generated, encoding="utf-8")
        return 0

    if not target.is_file():
        print(STALE_MESSAGE, file=sys.stderr)
        print(STALE_MESSAGE)
        return 1

    actual = target.read_text(encoding="utf-8")
    if actual == generated:
        return 0

    print(STALE_MESSAGE, file=sys.stderr)
    print(STALE_MESSAGE)
    if args.verbose:
        for line in _first_diff_lines(generated, actual):
            print(line)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
