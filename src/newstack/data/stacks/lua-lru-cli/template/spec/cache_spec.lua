package.path = "./src/?.lua;./src/?/init.lua;" .. package.path
local harness = require("spec.harness")
local lru = require("lru")

harness.describe("cache", function()
  harness.it("stores and retrieves", function()
    local c = lru.new(2)
    lru.put(c, "a", 1)
    lru.put(c, "b", 2)
    harness.eq(lru.get(c, "a"), 1)
    harness.eq(lru.get(c, "b"), 2)
  end)

  harness.it("evicts lru on capacity", function()
    local c = lru.new(2)
    lru.put(c, "a", 1)
    lru.put(c, "b", 2)
    lru.put(c, "c", 3)
    harness.eq(lru.get(c, "a"), nil)
    harness.eq(lru.get(c, "b"), 2)
    harness.eq(lru.get(c, "c"), 3)
  end)

  harness.it("get updates recency", function()
    local c = lru.new(2)
    lru.put(c, "a", 1)
    lru.put(c, "b", 2)
    lru.get(c, "a")
    lru.put(c, "c", 3)
    harness.eq(lru.get(c, "a"), 1)
    harness.eq(lru.get(c, "b"), nil)
  end)

  harness.it("stats track hits misses puts", function()
    local c = lru.new(2)
    lru.put(c, "a", 1)
    lru.get(c, "a")
    lru.get(c, "z")
    local s = lru.stats(c)
    harness.eq(s.puts, 1)
    harness.eq(s.hits, 1)
    harness.eq(s.misses, 1)
    harness.eq(s.size, 1)
  end)

  harness.it("update existing keeps capacity", function()
    local c = lru.new(1)
    lru.put(c, "a", 1)
    lru.put(c, "a", 2)
    harness.eq(lru.get(c, "a"), 2)
    harness.eq(lru.stats(c).size, 1)
  end)
end)