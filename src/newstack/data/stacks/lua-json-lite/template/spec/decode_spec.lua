local harness = require("spec.harness")
local ljson = require("ljson")
local describe, it, eq = harness.describe, harness.it, harness.eq

describe("decode", function()
  it("reads scalars", function()
    eq(ljson.parse("true"), true)
    eq(ljson.parse("false"), false)
    eq(ljson.parse("null"), ljson.null)
    eq(ljson.parse("42"), 42)
    eq(ljson.parse("-1.5e2"), -150)
    eq(ljson.parse('"hi"'), "hi")
  end)

  it("reads arrays and objects", function()
    local value = ljson.parse('{"a":[1,2,{"b":"c"}],"d":{}}')
    eq(value.a[1], 1)
    eq(value.a[2], 2)
    eq(value.a[3].b, "c")
    eq(#value.a, 3)
    eq(next(value.d), nil)
  end)

  it("keeps null inside arrays", function()
    local value = ljson.parse("[1,null,3]")
    eq(#value, 3)
    eq(value[2], ljson.null)
  end)

  it("decodes escapes and unicode", function()
    eq(ljson.parse('"a\\tb\\n\\"q\\""'), 'a\tb\n"q"')
    eq(ljson.parse('"\\u00e9"'), "\195\169")
    eq(ljson.parse('"\\ud83d\\ude00"'), "\240\159\152\128")
  end)

  it("accepts whitespace everywhere", function()
    eq(ljson.parse('  [\n 1 ,\t2 ]\n'), { 1, 2 })
  end)

  it("rejects trailing data", function()
    local ok, err = pcall(ljson.parse, "{} {}")
    eq(ok, false)
    assert(tostring(err):find("trailing", 1, true))
  end)

  it("rejects unterminated input", function()
    local ok, err = pcall(ljson.parse, '{"a": 1')
    eq(ok, false)
    assert(tostring(err):find("offset", 1, true))
  end)

  it("rejects control characters in strings", function()
    local ok = pcall(ljson.parse, '"a\nb"')
    eq(ok, false)
  end)

  it("rejects leading zeros", function()
    local ok = pcall(ljson.parse, "012")
    eq(ok, false)
  end)
end)
